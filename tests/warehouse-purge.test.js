import {readFileSync} from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {applyWarehousePurge,previewWarehousePurge} from '../Models/warehouse-purge.js';
const manifest=JSON.parse(readFileSync(new URL('../scripts/manufacturer-import-nov20-2026.manifest.json',import.meta.url),'utf8'));
const batch=manifest.batch;
const stock=()=>({inventory:[],catalog:manifest.items.map(e=>({id:e.id,sku:e.sku,type:'material',manufacturer:e.brand,
 manufacturerPartNumber:e.mpn,price:0,changePrice:0,cost:0,needsPricing:true})),events:[]});
const admin={role:'admin',email:'admin@example.test'};
const confirm=p=>({backupConfirmed:true,confirmation:'DELETE '+p.eligible,fingerprint:p.fingerprint});
test('only exact unprotected manifest records are removed; historical IDs/SKUs, zero stock and prices protect',()=>{
 const state=stock();
 const [a,b,c,d,e,f,g]=state.catalog;
 state.inventory=[{catalogId:a.id,quantity:0}];
 state.workorders=[{status:'paid',entries:[{catalogId:b.id}]}];
 state.trash=[{records:{[c.id]:{}}}];
 state.pricingProfiles=[{rates:{[d.sku.toLowerCase()]:10}}];
 e.price=33;
 f.warehouseArchiveBatch='other';
 g.warehouseArchived=true;
 g.warehouseArchiveBatch=batch;
 const original={...a,id:'cat-existing'};
 state.catalog.push(original);
 const snapshot=structuredClone(state);
 const preview=previewWarehousePurge(state,manifest);
 assert.deepEqual(state,snapshot);
 assert.equal(preview.eligible,3837);
 assert.equal(preview.protected,6);
 const result=applyWarehousePurge(state,manifest,admin,confirm(preview));
 assert.equal(result.deleted,3837);
 assert.deepEqual(state.catalog,[a,b,c,d,e,f,original]);
 assert.equal(state.events.length,1);
 assert.ok(!JSON.stringify(state.events).includes(g.id));
 assert.deepEqual(state.workorders,snapshot.workorders);
 assert.deepEqual(state.trash,snapshot.trash);
 assert.deepEqual(state.inventory,snapshot.inventory);
 assert.deepEqual(state.pricingProfiles,snapshot.pricingProfiles);
});
test('fails closed on identity drift, stale flags, request IDs, missing backup, or wrong phrase and role',()=>{
 const state=stock();
 const p=previewWarehousePurge(state,manifest);
 const req=confirm(p);
 assert.throws(()=>applyWarehousePurge(state,manifest,{role:'tech'},req),/Admin/);
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,{...req,ids:[state.catalog[0].id]}),/backup/);
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,{...req,backupConfirmed:false}),/backup/);
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,{...req,confirmation:'DELETE 0'}),/Typed/);
 state.catalog[0].warehouseArchived=false;
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,req),/stale/);
 state.catalog[0].sku='elsewhere';
 let changed=previewWarehousePurge(state,manifest);
 assert.equal(changed.drift,1);
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,confirm(changed)),/drift/);
 state.catalog.shift();
 changed=previewWarehousePurge(state,manifest);
 assert.equal(changed.missing,1);
 assert.throws(()=>applyWarehousePurge(state,manifest,admin,confirm(changed)),/drift/);
 assert.equal(state.events.length,0);
});

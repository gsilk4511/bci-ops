test('Eastern time handles seasonal UTC, leap months, and rejects skipped or ambiguous wall time',()=>{
 assert.equal(easternInstant(date,'08:00'),'2026-12-01T13:00:00.000Z');
 assert.equal(easternInstant('2026-08-01','08:00'),'2026-08-01T12:00:00.000Z');
 assert.throws(()=>easternInstant('2026-03-08','02:30'),/daylight/);
 assert.throws(()=>easternInstant('2026-11-01','01:30'),/daylight/);
 assert.equal(monthShift('2028-01-31',1),'2028-02-29');
 assert.equal(daySpan('2026-11-01','2027-01-31').length,92);
});
test('export is valid UTC snapshot and Outlook handoff is a separate encoded draft only',()=>{
 const state=sample();put(state);
 const order=view(state).orders[0],ics=scheduleIcs({...order,title:'Unicode é'.repeat(20)+'\nATTENDEE:injection@invalid.example'},new Date('2026-11-26T00:00:00Z'));
 assert.equal((ics.match(/BEGIN:VEVENT\r\n/g)||[]).length,2);
 assert.match(ics,/METHOD:PUBLISH\r\n/);
 assert.match(ics,/DTSTART:20261201T130000Z\r\n/);
 assert.match(ics,/DTEND:20261203T220000Z\r\n/);
 assert.doesNotMatch(ics,/\r\n(?:ATTENDEE|ORGANIZER):/);
 assert.ok(ics.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
 const href=new URL(outlookCompose({...visits[0],title:'Site visit',location:'10 Demo Road',notes:'<Friendly>\nThanks',recipient:'private@example.invalid'}));
 assert.equal(href.origin,'https://outlook.office.com');
 assert.equal(href.searchParams.get('startdt'),'2026-12-01T13:00:00.000Z');
 assert.equal(href.searchParams.get('body'),'&lt;Friendly&gt;<br>Thanks');
 assert.doesNotMatch(href.href,/private/);
});

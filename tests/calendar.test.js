 assert.equal(view(state,{...tech,permissions:[]}),undefined);
 assert.throws(()=>authorizePermission('workorder.schedule','tech',tech.permissions),/Permission denied/);
 assert.doesNotThrow(()=>authorizePermission('workorder.schedule','tech',[...tech.permissions,'workorder.update']));
 assert.throws(()=>applyAction(state,'workorder.schedule',{workorderId:'wo_second'},{...tech,permissions:[...tech.permissions,'workorder.update']}),/scope/);

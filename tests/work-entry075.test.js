test('time is authenticated, needs notes, and own-row edit reroutes reviewed work',()=>{
 const {state,order,run}=fixture(),time={date:'2026-11-19',type:'labor',catalogId:'cat_3',startTime:'08:00',endTime:'10:00',tech:'Supplied identity'};
 assert.throws(()=>run('entry.add',{...time,description:'  '}),/Work notes/);
 const entry=run('entry.add',{...time,description:'Installed drops'});
 assert.equal(entry.employeeEmail,employee.email);
 assert.notEqual(entry.tech,'Supplied identity');
 const patch={entryId:entry.id,revision:'',...time,endTime:'10:30',description:'Installed and labeled drops'};
 assert.throws(()=>run('entry.update',patch,other),/own account|your account/);
 run('workorder.close');run('workorder.review',{},admin);
 run('entry.update',patch);
 assert.equal(order.entries[0].quantity,2.5);
 assert.equal(order.entryHistory[0].before.quantity,2);
 assert.equal(order.closeoutHistory[0].reviewedBy,admin.email);
 assert.equal(order.status,'ready-for-review');
 assert.equal(state.tickets.find(t=>t.kind==='review').status,'Ready for review');
 assert.throws(()=>run('entry.update',patch),/changed/);
 state.payrollRuns=[{start:'2026-11-16',end:'2026-11-22'}];
 assert.throws(()=>run('entry.remove',{entryId:entry.id,revision:order.entries[0].revision,confirmation:'remove',reason:'Duplicate'}),/approved/);
});
test('receipts are linked without duplicate purchase and archive restores stock, payroll, receipts and ticket',()=>{
 const {state,order,run}=fixture(),uploadId='12345678-1234-1234-1234-123456789012';
 const buy={catalogId:'cat_2',quantity:2,location:'Shop',type:'material',receipt:{content:png,uploadId},submissionId:uploadId};
 const entry=run('entry.add',buy);
 assert.equal(run('entry.add',buy).id,entry.id);
 assert.equal(state.inventory[0].quantity,2);
 assert.equal(order.receipts[0].entryId,entry.id);
 const file=order.receipts[0];
 assert.equal(readWorkReceipt(state,{workorderId:order.id,id:file.id}).content,png);
 assert.equal(visibleState(state,'admin',['workorders.view']).workorderReceiptData,undefined);
 assert.equal(order.receipts[0].content,undefined);
 assert.equal(state.purchases.length,0);
 run('entry.update',{entryId:entry.id,revision:'',quantity:3,date:entry.date,description:'Used 3 jacks'});
 assert.equal(state.inventory[0].quantity,1);
 const labor=run('entry.add',{catalogId:'cat_3',type:'labor',quantity:2,date:'2026-11-19',description:'Installed jacks'});
 run('workorder.close');
 const [plan]=previewWorkorderRemoval(state,[order.id]);
 const deletion={ids:[order.id],reason:'Archived obsolete job',confirmation:'delete',revisions:{[order.id]:plan.revision}};
 assert.throws(()=>run('workorder.delete',deletion),/Admin/);
 assert.throws(()=>run('workorder.delete',{...deletion,confirmation:''},admin),/Type delete/);
 assert.throws(()=>run('workorder.delete',{...deletion,revisions:{}},admin),/Review the current/);
 run('workorder.delete',deletion,admin);
 assert.equal(state.inventory[0].quantity,4);
 assert.equal(state.workorders.length,0);
 assert.equal(state.tickets.length,0);
 assert.equal(state.payrollOther[0].id,labor.id);
 assert.equal(payrollPreview(state,'2026-11-19','2026-11-19').rows[0].work,2);
 assert.throws(()=>readWorkReceipt(state,{workorderId:order.id,id:file.id}),/unavailable/);
 assert.throws(()=>run('trash.purge',{ids:[state.trash[0].id],confirmation:'PERMANENTLY DELETE'},admin),/operational history/);
 run('trash.restore',{ids:[state.trash[0].id]},admin);
 assert.equal(state.inventory[0].quantity,1);
 assert.equal(state.tickets[0].workorderId,order.id);
 assert.equal(state.payrollOther.length,0);
 assert.equal(state.workorders[0].receipts[0].id,file.id);
 assert.equal(readWorkReceipt(state,{workorderId:order.id,id:file.id}).content,png);
 assert.throws(()=>authorizePermission('receipt.read','tech',['tickets.view']),/denied/i);
 assert.throws(()=>authorizePermission('workorder.delete','tech',['workorder.delete','workorders.view']),/Admin/);
});

import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {applyAction,seed} from '../Models/lib.js';
import {authorizePermission} from '../Models/permissions.js';
import {scopeState,authorizeRecordAction} from '../Models/record-scope.js';
import {previewWorkorderRemoval} from '../Models/records.js';
import {readWarehouseReceipt,warehouseFieldPurchases} from '../Models/warehouse-receipts.js';
import {visibleState} from '../Models/visibility.js';

const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAACklEQVR4nGNgAAAAAgABSK+kcQAAAABJRU5ErkJggg==';
const admin={email:'warehouse@example.invalid',role:'admin',permissions:['inventory.view','inventory.receive','workorders.view','receipt.read','receipt.add','finance.view']};
const office={...admin,role:'office',permissions:['inventory.view','inventory.receive','workorders.view','receipt.read']};
const catalogId='cat_2';
const issue=(state,order,fields={})=>applyAction(state,'entry.add',{workorderId:order.id,type:'material',catalogId,quantity:2,...fields},admin);
const open=state=>Object.assign(state.workorders[0],{approvedAt:'2026-11-11',status:'released',createdBy:'field@example.invalid'});
const upload=()=>({content:png,uploadId:randomUUID()});
const project=(state,actor=admin)=>warehouseFieldPurchases(state,scopeState(state,actor),actor);
const count=state=>state.inventory.find(row=>row.catalogId===catalogId).quantity;
const addPhoto=(state,order,entryId)=>applyAction(state,'receipt.add',{workorderId:order.id,entryId,...upload()},admin).id;

test('direct Warehouse receipt is atomic, retry-safe, timestamped, and readable by receiving staff without finance access',()=>{
 const state=seed();
 const data={warehouseReceive:true,catalogId,quantity:3,vendor:'Supply House',submissionId:randomUUID(),receipt:upload()};
 authorizePermission('inventory.receive','office',office.permissions,data);
 assert.throws(()=>authorizePermission('inventory.receive','office',office.permissions,{...data,unitCost:10}),/Finance access/);
 assert.throws(()=>applyAction(state,'inventory.receive',{...data,receipt:{content:'AAAA'}},office),/JPEG or PNG/);
 assert.equal(count(state),4);
 assert.equal(state.purchases.length,0);
 const purchase=applyAction(state,'inventory.receive',data,office);
 const again=applyAction(state,'inventory.receive',data,office);
 assert.deepEqual(purchase,again);
 assert.throws(()=>applyAction(state,'inventory.receive',{...data,quantity:5},office),/already recorded/);
 assert.match(purchase.at,/^\d{4}-\d{2}-\d{2}T\d{2}:/);
 assert.equal(state.purchases[0].unitCost,null);
 assert.equal(state.movements[0].warehouseReceiptId,purchase.receiptId);
 assert.equal(state.movements[0].quantity,3);
 assert.equal(state.movements[0].at,purchase.at);
 assert.equal(state.purchases.length,1);
 assert.equal(count(state),7);
 assert.equal(readWarehouseReceipt(state,scopeState(state,office),office,{id:purchase.receiptId}).content,png);
 const viewOnly={...office,permissions:['inventory.view']};
 assert.throws(()=>readWarehouseReceipt(state,scopeState(state,viewOnly),viewOnly,{id:purchase.receiptId}),/unavailable/);
 assert.equal('workorderReceiptData' in visibleState(state,'admin',admin.permissions),false);
 assert.equal('warehouseReceiptId' in visibleState(state,'office',viewOnly.permissions).movements[0],false);
});

test('field material purchase is linked to an existing issue, credited once and never undone by archive/restore',()=>{
 const state=seed(), order=open(state);
 const entry=issue(state,order,{receipt:upload()});
 assert.equal(count(state),2);
 const linked=project(state).find(line=>line.entryId===entry.id);
 assert.equal(linked.status,'pending');
 assert.equal(linked.quantity,2);
 assert.equal(state.purchases.length,0);
 const duplicate=addPhoto(state,order,entry.id);
 assert.equal(project(state).find(row=>row.id===duplicate).status,'review');
 assert.throws(()=>applyAction(state,'inventory.commitFieldPurchase',{...linked,revision:'stale'},admin),/source material entry changed/i);
 const posted=applyAction(state,'inventory.commitFieldPurchase',linked,admin);
 assert.equal(posted.quantity,2);
 assert.equal(count(state),4);
 assert.equal(state.movements[0].sourceWorkorderId,order.id);
 assert.equal(state.movements[0].workorderId,null);
 assert.equal(state.purchases.length,0);
 assert.equal(order.entries.length,1);
 assert.equal(Object.keys(state.workorderReceiptData).length,2);
 assert.equal(applyAction(state,'inventory.commitFieldPurchase',linked,admin).existing,true);
 assert.equal(project(state).find(line=>line.id===linked.id).status,'committed');
 assert.equal(count(state),4);

 const denial={...office,recordScopes:{workorders:'own'}};
 assert.deepEqual(project(state,denial),[]);
 assert.throws(()=>authorizeRecordAction(state,denial,'inventory.commitFieldPurchase',linked),/scope/);
 assert.throws(()=>readWarehouseReceipt(state,scopeState(state,denial),denial,{id:linked.id}),/unavailable/);
 const scopedMovement=visibleState(scopeState(state,denial),'office',denial.permissions).movements.find(row=>row.id===posted.movementId);
 assert.equal(scopedMovement.type,'field-purchase');
 assert.equal(scopedMovement.warehouseReceiptId,undefined);
 assert.equal(scopedMovement.sourceWorkorderTitle,undefined);

 const preview=previewWorkorderRemoval(state,[order.id])[0];
 assert.deepEqual(preview.blockers,[]);
 applyAction(state,'workorder.delete',{ids:[order.id],confirmation:'delete',reason:'Wrong job',revisions:{[order.id]:preview.revision}},admin);
 assert.equal(count(state),6);
 assert.equal(project(state).find(row=>row.id===linked.id).archived,true);
 assert.equal(readWarehouseReceipt(state,scopeState(state,admin),admin,{id:linked.id}).content,png);
 assert.throws(()=>readWarehouseReceipt(state,scopeState(state,office),office,{id:linked.id}),/unavailable/);
 const archived=state.trash.find(item=>item.record.id===order.id);
 applyAction(state,'trash.restore',{ids:[archived.id]},admin);
 assert.equal(count(state),4);
 assert.equal(project(state).find(row=>row.id===linked.id).status,'committed');
});

test('general and ambiguous older receipts never add stock; carefully matched legacy lines remain usable',()=>{
 const state=seed(), order=open(state);
 const entry=issue(state,order);
 const generic=addPhoto(state,order,null);
 assert.equal(project(state).some(row=>row.id===generic),false);
 const legacy=addPhoto(state,order,entry.id);
 const legacyPhoto=order.receipts.find(row=>row.id===legacy);
 delete legacyPhoto.materialAtUpload;
 assert.equal(project(state).find(row=>row.id===legacy).status,'pending');
 const before=project(state).find(row=>row.id===legacy);
 applyAction(state,'entry.update',{workorderId:order.id,entryId:entry.id,date:entry.date,quantity:3,revision:'',description:'Corrected issue'},admin);
 assert.equal(project(state).find(row=>row.id===legacy).status,'review');
 assert.throws(()=>applyAction(state,'inventory.commitFieldPurchase',before,admin),/unchanged Warehouse material issue/);
 const fresh=addPhoto(state,order,entry.id);
 const freshRow=project(state).find(row=>row.id===fresh);
 assert.equal(freshRow.status,'pending');
 assert.equal(freshRow.quantity,3);
 assert.throws(()=>authorizePermission('inventory.commitFieldPurchase','office',['inventory.view','inventory.receive'],freshRow),/Work-order receipt access/);
 assert.throws(()=>authorizePermission('entry.add','office',['workorders.view','entry.add'],{receipt:upload()}),/upload permission/);
 const altered=order.entries.find(row=>row.id===entry.id);
 applyAction(state,'entry.remove',{workorderId:order.id,entryId:entry.id,reason:'Wrong part',confirmation:'remove',revision:altered.revision},admin);
 assert.equal(project(state).find(row=>row.id===fresh).status,'review');
 assert.equal(readWarehouseReceipt(state,scopeState(state,admin),admin,{id:fresh}).content,png);
 assert.equal(count(state),4);
});
